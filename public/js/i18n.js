/** 저장된 언어 → 없으면 한국어(기본값). */
function readLang() {
  try { const v = localStorage.getItem(STORAGE_KEY); if (LANGS.includes(v)) return v; } catch { /* 저장소를 못 쓰는 환경 */ }
  return DEFAULT_LANG;
}
let current = readLang();

export const getLang = () => current;

export function setLang(lang) {
  if (!LANGS.includes(lang)) return;
  current = lang;
  try { localStorage.setItem(STORAGE_KEY, lang); } catch { /* 무시 */ }
}

/** 키에 해당하는 문구. {이름} 자리에 vars 값을 넣는다. 키가 없으면 키를 그대로 돌려준다. */
export function t(key, vars = {}) {
  const text = MESSAGES[current][key] ?? MESSAGES[DEFAULT_LANG][key] ?? key;
  return text.replace(/\{(\w+)\}/g, (_, k) => (vars[k] != null ? String(vars[k]) : ""));
}

/** 서버 데이터의 표시 문구: 문자열이면 그대로, { ko, en } 이면 현재 언어로. */
export function pick(value) {
  if (value && typeof value === "object") return value[current] ?? value[DEFAULT_LANG] ?? value.en ?? "";
  return value == null ? "" : String(value);
}

/** HTML 의 data-i18n* 속성을 읽어 정적 문구를 현재 언어로 바꾼다. */
export function applyStatic(root = document) {
  document.documentElement.lang = current;
  for (const el of root.querySelectorAll("[data-i18n]")) el.textContent = t(el.dataset.i18n);
  for (const el of root.querySelectorAll("[data-i18n-placeholder]")) el.placeholder = t(el.dataset.i18nPlaceholder);
  for (const el of root.querySelectorAll("[data-i18n-title]")) el.title = t(el.dataset.i18nTitle);
  for (const el of root.querySelectorAll("[data-i18n-aria]")) el.setAttribute("aria-label", t(el.dataset.i18nAria));
  for (const el of root.querySelectorAll("[data-i18n-alt]")) el.alt = t(el.dataset.i18nAlt);
}
